#include <stdio.h>
int main() {

    /*
     Structure of variable declaration

     Data type Variable_Name = Value;
    */


    // Integer variable
    int age = 23; 

    // Floating-point variable
    float my_height = 5.11;

    // Double variable
    double PI = 3.14159;

    // Character variable
    char cgpa = 'A';
    
    printf("My age is %d \n", age);
    printf("Height: %f\n", my_height);
    printf("Value of PI: %1f\n", PI);
    printf("CGPA: %c", cgpa);

    return 0;
}